import { supabase } from "../config/supabase.js";
import {
  generateFoodSuggestionsFromPantry,
  generateRecipeDetail,
} from "../services/gemini.service.js";
import { findMealImageByTitleService } from "../services/mealdb.service.js";

export const getRecipeSuggestionsFromPantry = async (req, res) => {
  const userId = req.user.id;

  const { data: pantry, error } = await supabase
    .from("pantry_items")
    .select("name, quantity")
    .eq("user_id", userId);

  if (error) return res.status(400).json({ error: error.message });

  if (!pantry || pantry.length === 0) {
    return res.status(400).json({ error: "Pantry kosong" });
  }

  try {
    const result = await generateFoodSuggestionsFromPantry(pantry);

    // Fetch images for the generated suggestions
      const suggestionsWithImages = await Promise.all(
        (result.suggestions || []).map(async (suggestion) => {
          let imageUrl = null;
          // Hanya cari gambar ke MealDB jika AI mencomot dari referensi MealDB (bahasa Inggris)
          if (suggestion.original_mealdb_name && suggestion.original_mealdb_name.trim() !== "") {
            imageUrl = await findMealImageByTitleService(suggestion.original_mealdb_name);
          }
          
          return {
            ...suggestion,
            image_url: imageUrl || null,
          };
        })
      );

    res.json({
      message: "Recipe suggestions generated by AI from pantry",
      pantry,
      suggestions: suggestionsWithImages,
    });
  } catch (error) {
    console.error("Error generating recipe suggestions:", error);
    res.status(500).json({
      error: "Failed to generate recipe suggestions",
      detail: error.message,
    });
  }
};

export const generateRecipe = async (req, res) => {
  const userId = req.user.id;
  const { title, category, cuisine, image_url } = req.body;

  if (!title) {
    return res.status(400).json({
      error: "Recipe title is required",
    });
  }

  const normalizedTitle = title.trim();

  const { data: existingRecipes, error: findError } = await supabase
    .from("recipes")
    .select("*")
    .eq("title", normalizedTitle)
    .limit(1);

  if (findError) {
    return res.status(400).json({ error: findError.message });
  }

  if (existingRecipes && existingRecipes.length > 0) {
    return res.json({
      source: "database",
      recipe: existingRecipes[0],
    });
  }

  const { data: pantry, error: pantryError } = await supabase
    .from("pantry_items")
    .select("name, quantity")
    .eq("user_id", userId);

  if (pantryError) {
    return res.status(400).json({ error: pantryError.message });
  }

  try {
    let imageUrl = image_url || await findMealImageByTitleService(normalizedTitle);

    const aiRecipe = await generateRecipeDetail({
      title: normalizedTitle,
      category,
      cuisine,
      pantryItems: pantry || [],
      image_url: imageUrl || null,
    });

    const finalRecipe = {
      ...aiRecipe,
      title: normalizedTitle,
      category: category || aiRecipe.category,
      cuisine: cuisine || aiRecipe.cuisine,
      image_url: imageUrl || null,
    };

    const { data: savedRecipe, error: saveError } = await supabase
      .from("recipes")
      .insert([
        {
          author: userId,
          title: finalRecipe.title,
          description: finalRecipe.description,
          cuisine: finalRecipe.cuisine,
          category: finalRecipe.category,
          ingredients: finalRecipe.ingredients,
          instructions: finalRecipe.instructions,
          image_url: finalRecipe.image_url,
          prep_time: finalRecipe.prep_time,
          cook_time: finalRecipe.cook_time,
          servings: finalRecipe.servings,
          nutrition: finalRecipe.nutrition,
          tips: finalRecipe.tips,
          is_public: false,
        },
      ])
      .select();

    if (saveError) {
      return res.status(400).json({ error: saveError.message });
    }

    res.json({
      source: "ai",
      message: "Recipe generated by AI and saved to database",
      recipe: savedRecipe[0],
    });
  } catch (error) {
    console.error("Error generating recipe detail:", error);
    res.status(500).json({
      error: "Failed to generate recipe with AI",
      detail: error.message,
    });
  }
};
